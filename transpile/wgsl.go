package transpile

import (
	"fmt"
	"go/types"
	"strings"

	"github.com/gogpu/naga/valid"
	"github.com/gogpu/naga/wgsl"
)

const WorkgroupSize = 64

var wgslTypes = map[types.BasicKind]string{
	types.Float32: "f32",
	types.Uint32:  "u32",
	types.Int32:   "i32",
}

// Generate returns the WGSL shader for kernel name with the given parameters.
//
// Binding 0 is a uniform struct holding the thread count followed by the
// scalar parameters. Each slice parameter gets the next binding.
func Generate(name string, params []Param) string {
	var b strings.Builder
	b.WriteString("// Code generated by gpugen. DO NOT EDIT.\n\n")

	b.WriteString("struct Params {\n    gpu_n: u32,\n")
	for i, p := range params {
		if p.Kind == ParamScalar {
			fmt.Fprintf(&b, "    %s: %s,\n", ident(p.Name, i), wgslTypes[p.Type])
		}
	}
	b.WriteString("}\n\n")

	b.WriteString("@group(0) @binding(0) var<uniform> params: Params;\n")
	binding := 1
	for i, p := range params {
		if p.Kind == ParamSlice {
			fmt.Fprintf(&b, "@group(0) @binding(%d) var<storage, read_write> %s: array<%s>;\n",
				binding, ident(p.Name, i), wgslTypes[p.Type])
			binding++
		}
	}
	b.WriteString("\n")

	fmt.Fprintf(&b, "@compute @workgroup_size(%d)\n", WorkgroupSize)
	fmt.Fprintf(&b, "fn %s(@builtin(global_invocation_id) gpu_gid: vec3<u32>) {\n", name)
	fmt.Fprintf(&b, "    let %s = gpu_gid.x;\n", ident(params[0].Name, 0))
	fmt.Fprintf(&b, "    if %s >= params.gpu_n {\n        return;\n    }\n", ident(params[0].Name, 0))
	b.WriteString("}\n")

	return b.String()
}

// ident returns a WGSL name for parameter i. WGSL doesn't allow "_".
func ident(name string, i int) string {
	if name == "" || name == "_" {
		return fmt.Sprintf("gpu_unused%d", i)
	}
	return name
}

// Validate parses and validates src with naga.
func Validate(name, src string) error {
	m, _, err := wgsl.Parse(src, wgsl.ParseOptions{})
	if err != nil {
		if pe, ok := err.(*wgsl.ParseError); ok {
			return fmt.Errorf("%s", pe.Format(src, name+".wgsl"))
		}
		return err
	}
	_, err = valid.Validate(m, valid.Options{})
	return err
}
